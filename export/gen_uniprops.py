# -*- coding: utf-8 -*-
"""Generate intern_decide/_uniprops.py.

Qwen's pre-tokenizer regex uses \\p{L}, \\p{N}, \\p{M} and \\s, which Python's
`re` cannot express and the `regex` package would -- but `regex` is a dependency
we do not want. The classes are instead expanded to explicit codepoint ranges
here, once, and embedded in the runtime as a generated table.

Run with any Python 3.12; the tables depend only on that build's `unicodedata`.
"""
import pathlib
import sys
import unicodedata

OUT = pathlib.Path(__file__).resolve().parents[1] / "intern_decide" / "_uniprops.py"

# Unicode general categories behind each Rust regex class.
CATEGORIES = {
    "L": {"Lu", "Ll", "Lt", "Lm", "Lo"},
    "N": {"Nd", "Nl", "No"},
    "M": {"Mn", "Mc", "Me"},
}

# Unicode White_Space=Yes. Rust's \s and char::is_whitespace use this property;
# Python's re.UNICODE \s additionally matches U+001C..U+001F, so it is listed
# explicitly rather than inherited from Python.
WHITE_SPACE = sorted(
    {0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x20, 0x85, 0xA0, 0x1680, 0x2028, 0x2029,
     0x202F, 0x205F, 0x3000, *range(0x2000, 0x200B)}
)


def ranges(codepoints):
    """Collapse a sorted iterable of codepoints into (start, end) ranges."""
    out = []
    for cp in codepoints:
        if out and cp == out[-1][1] + 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return [tuple(r) for r in out]


def collect():
    buckets = {name: [] for name in CATEGORIES}
    for cp in range(sys.maxunicode + 1):
        cat = unicodedata.category(chr(cp))
        for name, cats in CATEGORIES.items():
            if cat in cats:
                buckets[name].append(cp)
    return {name: ranges(cps) for name, cps in buckets.items()}


def literal(rs):
    """Ranges as a compact string of codepoint pairs, decoded at import."""
    return "".join("%05x%05x" % r for r in rs)


def main():
    tables = collect()
    tables["S"] = ranges(WHITE_SPACE)
    lines = [
        "# -*- coding: utf-8 -*-",
        '"""Generated by export/gen_uniprops.py -- do not edit.',
        "",
        "Codepoint ranges for the Unicode classes Qwen's pre-tokenizer regex needs",
        "(\\\\p{L}, \\\\p{N}, \\\\p{M}) plus White_Space, packed as 5-hex-digit pairs.",
        '"""',
        "",
        "__all__ = [\"RANGES\", \"char_body\", \"char_class\"]",
        "",
        "_PACKED = {",
    ]
    for name in ("L", "N", "M", "S"):
        lines.append(f'    "{name}": (')
        blob = literal(tables[name])
        for i in range(0, len(blob), 90):
            lines.append(f'        "{blob[i:i + 90]}"')
        lines.append("    ),")
    lines += [
        "}",
        "",
        "",
        "def _unpack(blob):",
        "    return [",
        "        (int(blob[i : i + 5], 16), int(blob[i + 5 : i + 10], 16))",
        "        for i in range(0, len(blob), 10)",
        "    ]",
        "",
        "",
        "RANGES = {name: _unpack(blob) for name, blob in _PACKED.items()}",
        "",
        "",
        "def _escape(cp):",
        "    return chr(cp) if 0x20 < cp < 0x7F and chr(cp) not in \"\\\\^]-\" else \"\\\\u%04x\" % cp",
        "",
        "",
        "def char_body(*names):",
        '    """Range list for the named classes, for inlining inside a [...] class."""',
        "    body = []",
        "    for name in names:",
        "        for lo, hi in RANGES[name]:",
        "            if hi > 0xFFFF:",
        "                body.append(\"\\\\U%08x-\\\\U%08x\" % (lo, hi) if lo != hi else \"\\\\U%08x\" % lo)",
        "            else:",
        "                body.append(_escape(lo) + \"-\" + _escape(hi) if lo != hi else _escape(lo))",
        '    return "".join(body)',
        "",
        "",
        "def char_class(*names, negate=False):",
        '    """A Python `re` character class covering the named Unicode classes."""',
        '    return "[" + ("^" if negate else "") + char_body(*names) + "]"',
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    total = sum(len(v) for v in tables.values())
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes, {total} ranges)")
    for name, rs in tables.items():
        print(f"  {name}: {len(rs)} ranges")


if __name__ == "__main__":
    main()
